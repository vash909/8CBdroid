#!/usr/bin/env python3
"""Generate offline CB country data and differential fixtures from pinned desktop C++ lookup."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT/'reference/wsjtcb'
DATA = ROOT/'core/src/main/resources/wsjtcb/countries.tsv'
FIXTURE = ROOT/'core/src/test/resources/wsjtcb/country-cases.tsv'


def inputs():
    manifest = json.loads((REF/'context-sources.json').read_text())
    qso = json.loads((REF/'qso-sources.json').read_text())
    assert manifest['schema'] == 1 and manifest['revision'] == qso['revision'] and manifest['repository'] == qso['repository']
    for item in manifest['files']:
        assert hashlib.sha256((REF/item['local']).read_bytes()).hexdigest() == item['sha256'], item['path']
    source = (REF/'source/context/AD1CCty.cpp').read_text()
    start = source.index('  std::map<QString, QString> const& cb_NNN_to_country ()')
    end = source.index('\n}\n\nstruct entity', start)
    methods = source[start:end]
    pairs = re.findall(r'\{"([0-9]{3})", "([^"\n]+)"\}', methods)
    assert len(pairs) == 350 and len(dict(pairs)) == 350
    return manifest, methods, pairs


def generate(optimization='O0'):
    manifest, methods, pairs = inputs()
    cases = [f'{n:03}AT001' for n in range(1000)]
    cases += [c['input'] for c in json.loads((REF/'cases.json').read_text())['cases'] if c['kind'] == 'C']
    cases += ['', ' 26at101 ', '1AT', '01AT', '001AT', '26AT', '026AT', '007AT1', '295AT1',
              '0AT1', '000AT1', '999ZZ/ZZ', '026AT/ZZ', '01AT1000', '1AT1000', '<26AT101>', '<...>', '3DA0']
    cases = list(dict.fromkeys(cases))
    with tempfile.TemporaryDirectory(prefix='wsjtcb-context-') as tmp:
        directory = Path(tmp); cpp = directory/'context.cpp'; exe = directory/'context'
        cpp.write_text('#include <map>\n#include <QString>\n#include <QTextStream>\n#include "Radio.hpp"\nnamespace {\n'+methods+'\n}\n'+'''
int main() {
  QTextStream input(stdin), output(stdout);
  while (!input.atEnd()) {
    auto line = input.readLine();
    auto call = QString::fromUtf8(QByteArray::fromHex(line.toLatin1()));
    output << Radio::cb_country_prefix(call) << "\\t" << cb_country_name_from_call(call) << "\\n";
  }
}
''')
        qt = subprocess.check_output(shlex.split(os.environ.get('PKG_CONFIG', 'pkg-config'))+['--cflags','--libs','Qt5Core'],text=True,timeout=15)
        subprocess.run(shlex.split(os.environ.get('CXX', 'g++'))+['-std=c++17','-'+optimization,'-fPIC',
            '-I',str(REF/'source/qso'),'-I',str(REF/'harness'),str(cpp),str(REF/'source/qso/Radio.cpp')]+
            shlex.split(qt)+shlex.split(os.environ.get('LDFLAGS',''))+['-o',str(exe)],check=True,timeout=60)
        rows = subprocess.check_output([str(exe)],input=''.join(c.encode().hex()+'\n' for c in cases),text=True,timeout=20).splitlines()
    assert len(rows) == len(cases)
    header = f"# WSJT-CB {manifest['revision']}; GPL-3.0-only; generated by scripts/wsjtcb_context.py\n"
    data = header+'# division\tdesktop country name\n'+''.join(f'{a}\t{b}\n' for a,b in pairs)
    fixture = header+'# input UTF-8 hex\tdivision\tdesktop country name\n'+''.join(c.encode().hex()+'\t'+row+'\n' for c,row in zip(cases,rows))
    return data, fixture, len(cases)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--data-only',action='store_true',help='Check data and source hashes without a C++ compiler')
    parser.add_argument('--optimization',choices=['O0','O2'],default='O0')
    args = parser.parse_args()
    if args.data_only:
        manifest, _, pairs = inputs()
        assert [tuple(line.split('\t')) for line in DATA.read_text().splitlines() if not line.startswith('#')] == pairs
        assert manifest['revision'] in FIXTURE.read_text().splitlines()[0]
        print('350 pinned CB divisions and source hashes verified.'); return
    data, fixture, count = generate(args.optimization)
    for path, content in [(DATA,data),(FIXTURE,fixture)]:
        if args.check: assert path.read_text() == content, f'Regenerate {path.name}'
        else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
    print(f'350 CB divisions and {count} original desktop lookup cases verified ({args.optimization}).')


if __name__ == '__main__': main()
